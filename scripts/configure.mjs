// Reads the operator's config and writes what the Worker is built from:
//   dist/config.json  page text, sites, pass-through hosts, resolved service icons
//   wrangler.toml     Worker name, routes and MAINTENANCE_UNTIL (generated; not committed)
//
// Config path: $MAINTENANCE_CONFIG, else ./maintenance.config.json, else the example.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import * as icons from "simple-icons";

const path = process.env.MAINTENANCE_CONFIG
  || (existsSync("maintenance.config.json") ? "maintenance.config.json" : "maintenance.config.example.json");
const cfg = JSON.parse(readFileSync(path, "utf8"));

const fail = (msg) => { console.error(`${path}: ${msg}`); process.exit(1); };
const str = (v) => typeof v === "string" && v.trim() !== "";
if (!str(cfg.worker?.name)) fail("worker.name is required");
if (!Array.isArray(cfg.routes) || !cfg.routes.every((r) => str(r.pattern) && str(r.zone))) fail("routes must be [{ pattern, zone }]");
if (!Array.isArray(cfg.sites) || !cfg.sites.length || !cfg.sites.every((s) => str(s.brand) && Array.isArray(s.hosts))) fail("sites must be [{ hosts, brand }]");
if (!str(cfg.timeZone?.id) || !str(cfg.timeZone?.label)) fail("timeZone needs id (IANA) and label");
try { new Intl.DateTimeFormat("en", { timeZone: cfg.timeZone.id }); } catch { fail(`unknown time zone ${cfg.timeZone.id}`); }
if (cfg.until && isNaN(Date.parse(cfg.until))) fail("until must be an ISO 8601 time");
const copyKeys = ["title", "status", "eyebrow", "headline", "body", "etaLabel", "soon", "left", "services", "hint"];
for (const [lang, c] of Object.entries(cfg.copy || {})) for (const k of copyKeys) if (!str(c[k])) fail(`copy.${lang}.${k} is required`);
if (!cfg.copy?.[cfg.defaultLanguage]) fail("defaultLanguage must be one of the copy languages");
for (const k of ["title", "subject", "eta", "etaUnknown", "owner", "site"]) if (!str(cfg.notice?.[k])) fail(`notice.${k} is required`);
if (!Array.isArray(cfg.notice.lines)) fail("notice.lines must be a list");

// Simple Icons slug -> export name: "apachekafka" -> siApachekafka
const services = (cfg.services || []).map(({ icon, name }) => {
  const si = icons[`si${icon.charAt(0).toUpperCase()}${icon.slice(1)}`];
  if (!si) fail(`services: no Simple Icons icon "${icon}" (see https://simpleicons.org for slugs)`);
  return { name: name || si.title, hex: si.hex, path: si.path };
});

mkdirSync("dist", { recursive: true });
const out = {
  passHosts: cfg.passHosts || [], until: cfg.until || "", timeZone: cfg.timeZone, defaultLanguage: cfg.defaultLanguage,
  sites: cfg.sites, copy: cfg.copy, notice: cfg.notice, services,
};
writeFileSync("dist/config.json", JSON.stringify(out, null, 2) + "\n");

const q = (s) => JSON.stringify(s);
writeFileSync("wrangler.toml", `# Generated by scripts/configure.mjs from ${path} -- edit that file instead.
name = ${q(cfg.worker.name)}
main = "src/index.ts"
compatibility_date = ${q(cfg.worker.compatibilityDate || "2026-09-01")}
rules = [{ type = "Text", globs = ["**/*.html", "**/*.txt"], fallthrough = false }]

# Deploying these routes turns maintenance ON; \`npx wrangler delete\` turns it OFF.
routes = [
${cfg.routes.map((r) => `  { pattern = ${q(r.pattern)}, zone_name = ${q(r.zone)} },`).join("\n")}
]

[build]
command = "npm run build"

[vars]
MAINTENANCE_UNTIL = ${q(cfg.until || "")}
`);
console.log(`configured from ${resolve(path)}: ${cfg.routes.length} route(s), ${services.length} service icon(s)`);
